// Bakes the thuluth lab's letter set into typed data: src/script/thuluth/letters.data.ts.
// The lab assembled its letter table at run time (hand-drawn forms, replaced per form by Calliar-learned ones, then by
// master fits, with the hand-drawn loop letters enlarged); this runs that assembly once, as the lab did for its
// references (useLearned(true, 1 / 1.25 * 1.12)), and records where each form came from.
//   node scripts/thuluth-letters.mjs        (development only: needs Playwright, see scripts/thuluth-lab.mjs)
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runLab } from './thuluth-lab.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const d = await runLab(`
  useLearned(true, 1 / 1.25 * 1.12);
  const prov = {};
  Object.keys(T).forEach(f => { prov[f] = {}; Object.keys(T[f]).forEach(form => {
    let src = 'hand';
    if ((LEARN_USE[f] || []).includes(form) && LEARNED[f] && LEARNED[f][form]) src = 'learned';
    if (FITTED[f] && FITTED[f][form]) src = 'master';
    if (f === 'sad' && USE_SAD_MASTER && SAD_MASTER[form]) src = 'master';
    if (f === 'qaf' && (form === 'ini' || form === 'med')) src = prov.fa[form];
    prov[f][form] = src; }); });
  return { table: JSON.parse(JSON.stringify(T)), prov, heh: HEH_FIN, great: GREAT };`);

const num = v => (Object.is(v, -0) ? '0' : String(v));
const pts = p => '[' + p.map(q => '[' + q.map(num).join(', ') + ']').join(', ') + ']';
const stroke = s => `{ ${s.ang != null ? `ang: ${s.ang}, ` : ''}${s.lean ? 'lean: true, ' : ''}pts: ${pts(s.pts)} }`;
const glyph = (g, src) =>
  `{ ${src ? `src: '${src}', ` : ''}exit: ${g.exit == null ? 'null' : num(g.exit)}, ${g.dotX != null ? `dotX: ${num(g.dotX)}, ` : ''}s: [${g.s.map(stroke).join(', ')}] }`;
const { finLong, ...tooth } = d.table.tooth;
const table = { ...d.table, tooth };
const out = [
  '// Generated by scripts/thuluth-letters.mjs from the thuluth lab (prototypes/thuluth-lab); do not edit by hand.',
  '// Letter skeletons in pen units (alif = 10 at BODY 1): points [x, y, width, corner], baseline y = 0, the connection',
  '// entering at (0, 0) from the right and leaving at `exit` on the left. Sources: hand (drawn in the lab), learned',
  '// (averaged from Calliar, MIT licence, ARBML; Alyafeai et al. 2021), master (fitted to photographs of historic works).',
  "import type { GlyphDef, LetterTable } from './types';",
  '',
  'export const LETTERS: LetterTable = {',
  ...Object.entries(table).map(
    ([f, forms]) =>
      `  ${f}: {\n${Object.entries(forms)
        .map(([form, g]) => `    ${form}: ${glyph(g, d.prov[f][form])},`)
        .join('\n')}\n  },`,
  ),
  '};',
  '',
  '/** A long, shallow final sweep for an emphasised ba (after the curves of tughra arms). */',
  `export const TOOTH_FIN_LONG: GlyphDef = ${glyph(finLong)};`,
  '',
  '/** Final heh after a connection, in its three designs (style.heh). */',
  'export const HEH_FIN: Record<string, GlyphDef> = {',
  ...Object.entries(d.heh).map(([k, g]) => `  ${k}: ${glyph(g)},`),
  '};',
  '',
  '/** Roundel-scale gestures fitted to the Husayn roundel in Hagia Sophia (Kazasker Mustafa Izzet): the great final nun',
  ' *  bowl and the long-headed initial hah. */',
  'export const GREAT = {',
  `  nunFin: ${glyph(d.great.nun.fin)},`,
  `  hahIni: ${glyph(d.great.hah.ini)},`,
  '} satisfies Record<string, GlyphDef>;',
  '',
];
writeFileSync(join(root, 'src/script/thuluth/letters.data.ts'), out.join('\n'));
console.log('wrote src/script/thuluth/letters.data.ts');
