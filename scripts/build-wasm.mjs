// Builds the WebAssembly kernels from their C sources and embeds them as base64 TypeScript modules
// (src/kernels/*.wasm.ts), so the engine can load them without a bundler plugin and tests run without a compiler.
//   node scripts/build-wasm.mjs
// Uses clang's wasm32 target (zig cc works the same: `zig cc -target wasm32-freestanding -O2 -mbulk-memory ...`).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const KERNELS = [{ name: 'seal', exports: ['buf', 'run'] }];
const tmp = mkdtempSync(join(tmpdir(), 'wasm-'));
for (const k of KERNELS) {
  const src = join(root, 'src/kernels', `${k.name}.c`),
    out = join(tmp, `${k.name}.wasm`);
  const cc = process.env.CC || 'clang';
  execFileSync(cc, [
    '--target=wasm32', '-O2', '-mbulk-memory', '-nostdlib', '-Wl,--no-entry', '-Wl,--export-memory',
    ...k.exports.map(e => `-Wl,--export=${e}`), '-o', out, src,
  ]);
  const bytes = readFileSync(out),
    hash = createHash('sha256').update(readFileSync(src)).digest('hex');
  writeFileSync(
    join(root, 'src/kernels', `${k.name}.wasm.ts`),
    `// Generated by scripts/build-wasm.mjs from ${k.name}.c; do not edit.\n` +
      `export const SOURCE_SHA256 = '${hash}';\n` +
      `export const WASM_BASE64 =\n  '${bytes.toString('base64')}';\n`,
  );
  console.log(`${k.name}.wasm: ${bytes.length} bytes`);
}
